create table if not exists companies (
    id bigint generated by default as identity primary key,
    name varchar(255) not null unique,
    company_code varchar(100) not null unique,
    contact_email varchar(255),
    ats_threshold integer default 60,
    client_count integer default 0,
    active boolean not null default true,
    subscription_plan varchar(50) default ''YEARLY'',
    price_per_employee numeric(12, 2) default 0,
    plan_price numeric(12, 2) default 0,
    contract_years integer default 1,
    renewal_date date
);

create table if not exists users (
    id bigint generated by default as identity primary key,
    username varchar(255) not null unique,
    password_hash varchar(255) not null,
    full_name varchar(255),
    email varchar(255),
    department varchar(255),
    designation varchar(255),
    role varchar(50) not null default ''EMPLOYEE'',
    company_id bigint,
    first_login boolean not null default true,
    face_enrolled boolean not null default false,
    active boolean not null default true,
    constraint fk_users_company foreign key (company_id) references companies(id)
);

create table if not exists projects (
    id bigint generated by default as identity primary key,
    name varchar(255),
    client_name varchar(255),
    team_size integer default 0,
    status varchar(50) default ''PLANNED'',
    company_id bigint,
    constraint fk_projects_company foreign key (company_id) references companies(id)
);

create table if not exists review_feedback (
    id bigint generated by default as identity primary key,
    reviewer_name varchar(255),
    rating integer,
    comment varchar(2000),
    created_at date,
    company_id bigint,
    constraint fk_feedback_company foreign key (company_id) references companies(id)
);

create table if not exists activity_logs (
    id bigint generated by default as identity primary key,
    username varchar(255),
    app_name varchar(255),
    active_seconds bigint not null default 0,
    logged_at timestamp
);

create index if not exists idx_users_company on users(company_id);
create index if not exists idx_users_role on users(role);
create index if not exists idx_projects_company on projects(company_id);
create index if not exists idx_projects_status on projects(status);
create index if not exists idx_feedback_company on review_feedback(company_id);
create index if not exists idx_activity_logs_username on activity_logs(username);